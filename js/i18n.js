  var current = 'vi';

  function t(key, vars) {
    var pack = STRINGS[current] || STRINGS.vi;
    var value = pack[key];
    if (value === undefined) { value = key; }
    if (vars) {
      Object.keys(vars).forEach(function (name) {
        value = value.split('{' + name + '}').join(vars[name]);
      });
    }
    return value;
  }

  function setLanguage(code) {
    if (!STRINGS[code]) { return; }
    current = code;
    document.documentElement.setAttribute('lang', code);
    apply();
    document.dispatchEvent(new CustomEvent('languagechange', { detail: { lang: code } }));
  }

  function getLanguage() { return current; }

  function apply(root) {
    var scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(function (node) {
      node.textContent = t(node.getAttribute('data-i18n'));
    });
    scope.querySelectorAll('[data-i18n-aria]').forEach(function (node) {
      node.setAttribute('aria-label', t(node.getAttribute('data-i18n-aria')));
    });
  }

  global.I18N = {
    t: t,
    apply: apply,
    setLanguage: setLanguage,
    getLanguage: getLanguage,
    available: Object.keys(STRINGS)
  };
